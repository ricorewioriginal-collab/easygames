export const worldOf = category => Object.keys(WORLDS).find(world => WORLDS[world].includes(category)) || category;

export const EVENTS = Object.entries(COLLECTIONS).flatMap(([category, block]) => block.trim().split('\n').map((line, index) => {
  const [title, year, info] = line.split('|');
  return { id: `${category}:${index}`, category, world: worldOf(category), title, year: Number(year), info };
}));

