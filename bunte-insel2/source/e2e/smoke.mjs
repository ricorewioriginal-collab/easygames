// Schneller Sichttest: Titel, neues Spiel, ein paar Sekunden laufen, Screenshots.
import { createRequire } from 'node:module';
const req = createRequire(import.meta.url);
let pw; for (const p of ['playwright', '/opt/node-tools/node_modules/playwright', '/opt/npm-tools/node_modules/playwright']) { try { pw = req(p); break; } catch {} }
const BASE = process.env.BASE || 'http://localhost:8090/bunte-insel2/';
const OUT = process.env.OUT || '/tmp/claude-0/shots';
const browser = await pw.chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
const errs = [];
page.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()); });
page.on('pageerror', e => errs.push('pageerror: ' + e.message));
const t0 = Date.now();
await page.goto(BASE + '?test=1');
await page.waitForFunction(() => window.__bi2, null, { timeout: 60000 });
console.log('Boot in', Date.now() - t0, 'ms');
await page.waitForTimeout(1500);
await page.screenshot({ path: OUT + '/01-title.png' });
await page.evaluate(() => { const b = window.__bi2; const { newSave } = b; });
await page.click('#btn-slots');
await page.waitForTimeout(400);
await page.screenshot({ path: OUT + '/02-slots.png' });
await page.click('#slot-1 .btn.green');
await page.waitForTimeout(400);
await page.click('#mode-story .btn');
await page.waitForTimeout(1200);
await page.screenshot({ path: OUT + '/03-editor.png' });
await page.fill('input[aria-label="Name"]', 'Testi');
await page.click('text=✔ Fertig');
await page.waitForTimeout(2500);
await page.screenshot({ path: OUT + '/04-start.png' });
await page.keyboard.down('KeyW'); await page.waitForTimeout(1800); await page.keyboard.up('KeyW');
await page.screenshot({ path: OUT + '/05-walk.png' });
const info = await page.evaluate(() => { const g = window.__bi2.g; return { pos: g.player.pos, world: g.currentWorld && g.currentWorld.id, calls: g.renderer.gl.info.render.calls, tris: g.renderer.gl.info.render.triangles, fps: g.renderer.fps }; });
console.log(JSON.stringify(info));
console.log(errs.slice(0, 20).join('\n'));
await browser.close();
